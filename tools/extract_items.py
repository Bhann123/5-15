"""Generates src/FimmFimmtan.Core/ItemTexts.cs from the Icelandic 5-15 questionnaire PDF."""
import os, re, sys
import pdfplumber

pdf = sys.argv[1] if len(sys.argv) > 1 else "docs/5-15_spurningalisti_2015_islenska.pdf"
with pdfplumber.open(pdf) as p:
    lines = [l.strip() for pg in p.pages[1:] for l in (pg.extract_text() or "").splitlines()]
stop = re.compile(r"^(daglegu lífi|Á ekki við|að nokkru|leyti við|Hamla|Hafa|Hamlar|alls ekki|Gott er|Lýstu|Nefndu|Einbeitingargeta|aðstæðum|Ef barnið|Geta barnsins|\(á |Foreldrum|Reynið|Skynjun,|á umheiminum|Grófhreyfingar|Fínhreyfingar|Hvatvísi|Félagsleg|við ýmiskonar|Geðræn|Verknaðir|Í þessu|sterkar|Tilgreindu|og hvernig|að mismunandi|\d+$|[.…]{5,})")
items, cur = {}, None
for l in lines:
    m = re.match(r"^(\d{1,3}) ?\. ?(.*)$", l)
    if m and 1 <= int(m.group(1)) <= 181 and int(m.group(1)) == (cur or 0) + 1:
        cur = int(m.group(1)); items[cur] = m.group(2); continue
    if cur and l and not stop.match(l) and cur not in (181,):
        items[cur] += " " + l
    elif cur and stop.match(l or "x"):
        pass
def clean(s):
    s = re.sub(r"[\uf000-\uf8ff\u25a1\u2610\u00a0\t]", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s.replace('"', '\\"')
assert len(items) == 181, len(items)
out = ["// <auto-generated> by tools/extract_items.py from the Icelandic 5-15 questionnaire. </auto-generated>",
       "namespace FimmFimmtan.Core;", "", "public static class ItemTexts", "{",
       "    public static string Get(int item) => item >= 1 && item <= Texts.Length ? Texts[item - 1] : \"\";", "",
       "    private static readonly string[] Texts =", "    ["]
out += [f'        "{clean(items[i])}",' for i in range(1, 182)]
out += ["    ];", "}", ""]
open("src/FimmFimmtan.Core/ItemTexts.cs", "w").write("\n".join(out))
