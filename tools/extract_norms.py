"""Generates src/FimmFimmtan.Core/NormData.cs from the norm PDFs (uploads/*_score_*.pdf)."""
import glob, os, re, sys
import pdfplumber

KEYS = {
    "Motor skills": "motor", "Gross motor skills": "motor.gross", "Fine motor skills": "motor.fine",
    "Executive functions": "exec", "Attention and concentration": "exec.attention",
    "Overactivity and impulsivity": "exec.hyper", "Passivity and inactivity": "exec.passivity",
    "Planning and organizing": "exec.planning", "Perception": "perc",
    "Perception of space and directions": "perc.space", "Concepts of time": "perc.time",
    "Perception of own body": "perc.body", "Perception of visual forms and figures": "perc.visual",
    "Memory": "memory", "Language": "lang", "Comprehension of spoken language": "lang.comprehension",
    "Expressive language": "lang.expressive", "Verbal communication": "lang.communication",
    "Learning": "learn", "Reading and writing": "learn.reading", "Arithmetic": "learn.arithmetic",
    "General learning": "learn.general", "Coping with learning": "learn.coping",
    "Social skills": "social", "Emotional/behavioral difficulties": "emo",
    "Internalisation": "emo.internal", "Acting out": "emo.acting", "Obsessive actions or thoughts": "emo.obsessive",
}
row = re.compile(r"^(.*?) ([\d.]+) ([\d.]+) ([\d.]+) ([\d.]+) ([\d.]+) ([\d.]+) ([\d.]+)$")
src = sys.argv[1] if len(sys.argv) > 1 else "uploads"
out = ["// <auto-generated> by tools/extract_norms.py from the 5-15 norm PDFs. Do not edit by hand. </auto-generated>",
       "namespace FimmFimmtan.Core;", "", "public static partial class Norms", "{",
       "    // key -> (Median, Mean, SD, P98, P90)", "    private static readonly Dictionary<(AgeGroup, Sex), Dictionary<string, Norm>> Data = new()", "    {"]
for f in sorted(glob.glob(os.path.join(src, "*_score*.pdf"))):
    name = os.path.basename(f)
    age, sex = re.match(r"(\d+-\d+)_(male|female)", name).groups()
    with pdfplumber.open(f) as p:
        text = "\n".join(pg.extract_text() for pg in p.pages)
    seen = {}
    for line in text.splitlines():
        m = row.match(line.strip())
        if m and m.group(1) in KEYS:
            key = KEYS[m.group(1)]
            seen[key] = [float(x) for x in m.groups()[3:]]
    assert len(seen) == len(KEYS), (name, set(KEYS.values()) - set(seen))
    group = "Age" + age.replace("-", "_")
    out.append(f"        [(AgeGroup.{group}, Sex.{'Male' if sex == 'male' else 'Female'})] = new()")
    out.append("        {")
    for key in KEYS.values():
        med, mean, sd, p98, p90 = seen[key]
        out.append(f'            ["{key}"] = new({med:.2f}, {mean:.2f}, {sd:.2f}, {p98:.2f}, {p90:.2f}),')
    out.append("        },")
out += ["    };", "}", ""]
dest = os.path.join(os.path.dirname(__file__), "..", "src", "FimmFimmtan.Core", "NormData.cs")
open(dest, "w").write("\n".join(out))
print("wrote", os.path.normpath(dest))
